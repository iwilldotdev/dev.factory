"""Argument parser of the command line; handlers live in cli.py."""
from __future__ import annotations

import argparse

DESC = "Take one ticket from intake to a draft change request; no step passes on a model's claim."


def build_parser() -> argparse.ArgumentParser:
    from .cli import (cmd_check, cmd_fetch, cmd_gate, cmd_human, cmd_ingest, cmd_init, cmd_log, cmd_media, cmd_next,
                      cmd_plan, cmd_reproduce, cmd_review, cmd_run, cmd_ship, cmd_runs, cmd_status, cmd_verify)
    from .cli_proof import cmd_baseline, cmd_confirm, cmd_feedback, cmd_metrics, cmd_uat
    from .cli_composite import cmd_claim, cmd_epic, cmd_mirror, cmd_review_run
    from .cli_design import cmd_design
    from .cli_env import cmd_env, cmd_wait
    from .guide import cmd_setup
    from .harness import IDS
    from .hook import cmd_hook
    p = argparse.ArgumentParser(prog="factory", description=DESC)
    p.add_argument("-V", "--version", action="store_true", help="print version and build identity")
    p.add_argument("--project", dest="project_pre", metavar="DIR", help="project directory (default: climb from the cwd)")
    sub = p.add_subparsers(dest="cmd", metavar="<command>")
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--project", metavar="DIR", help="project directory (default: climb from the cwd)")
    common.add_argument("--json", action="store_true", help="machine-readable output")
    common.add_argument("--actor", help="free-text hint stored in events (audit trail only)")
    scoped = argparse.ArgumentParser(add_help=False, parents=[common])
    scoped.add_argument("--run", metavar="RUN", help="run id (default: the only open run)")

    def add(name, func, help_, parents=(common,)):
        sp = sub.add_parser(name, help=help_, parents=list(parents))
        sp.set_defaults(func=func)
        return sp

    sp = add("init", cmd_init, "create factory.toml and .factory/ in a directory")
    sp.add_argument("--name", help="project name (default: the directory name)")
    sp.add_argument("--repo", action="append", metavar="PATH", help="repo path (repeat for a workspace; default .)")
    sp.add_argument("--base", default="main", help="base branch of the repos (default main)")
    sp.add_argument("--harness", default="none", help="write a harness adapter: " + ", ".join(IDS))
    sp.add_argument("--scope", default="project", choices=("project", "user"), help="project: write into the directory; user: into the host's user home (no project)")
    sp.add_argument("--hooks", action="store_true", help="also merge the optional hook entry into the host settings (the chat harness)")
    add("check", cmd_check, "validate the configuration")
    sp = add("setup", cmd_setup, "guided setup: checklist of the project config, or workspace facts with --discover")
    sp.add_argument("--discover", nargs="?", const="", metavar="DIR", help="print JSON facts of every git repo in DIR (default: the configured repos, else the cwd)")
    sp = add("status", cmd_status, "status of a run, or of the project with --config", [scoped])
    sp.add_argument("run_id", nargs="?")
    sp.add_argument("--config", action="store_true", help="show the effective configuration")
    add("runs", cmd_runs, "list runs")
    sp = add("log", cmd_log, "events of a run", [scoped])
    sp.add_argument("run_id", nargs="?")
    sp.add_argument("--tail", type=int, metavar="N")
    sp = add("next", cmd_next, "print the next required action (of an epic: the ready children)", [scoped])
    sp.add_argument("run_id", nargs="?")
    sp.add_argument("--session", help="your session hint: a run claimed by another session refuses")
    sp.add_argument("--takeover", action="store_true", help="take over a run claimed by another session")
    sp = add("claim", cmd_claim, "record the session that works on a run", [scoped])
    sp.add_argument("run_id", nargs="?")
    sp.add_argument("--session", help="your session hint (default: $FACTORY_SESSION)")
    sp.add_argument("--takeover", action="store_true", help="take over a run claimed by another session")

    rp = sub.add_parser("run", help="start, retype, close or delete a run").add_subparsers(dest="sub", required=True)
    for name, helptext in (("start", "open a run for a ticket"), ("retype", "change the run kind"), ("repos", "declare affected repos"),
                           ("branch", "create the run worktrees"), ("close", "end a run without gates"), ("delete", "remove a run, its clean worktrees and its branches with no commit of their own")):
        sp = rp.add_parser(name, help=helptext, parents=[common if name == "start" else scoped])
        sp.set_defaults(func=cmd_run)
        if name == "start":
            sp.add_argument("ticket")
            sp.add_argument("--kind", help="feature, bug, hotfix, epic or review (default: from the ticket contract)")
            sp.add_argument("--repos", help="affected repos, comma separated")
        elif name == "retype":
            sp.add_argument("--kind", required=True)
        elif name == "repos":
            sp.add_argument("names", help="comma separated repo names")
        elif name == "branch":
            sp.add_argument("--repos", help="repos to branch (default: the declared repos)")
            sp.add_argument("--from-run", metavar="RUN", help="start the branch at the head of this run's worktree (a stacked branch)")
        elif name == "close":
            sp.add_argument("--reason", required=True)
        else:
            sp.add_argument("run_id", nargs="?")
            sp.add_argument("--yes", action="store_true", help="confirm the removal")
            sp.add_argument("--decision", help="the user's recorded decision (D-n), needed when the run spent loops or has open blockers")
    sp = add("ask", cmd_human, "open a question for the user", [scoped])
    sp.add_argument("text")
    sp.add_argument("--ref", help="e.g. attachment:<id>")
    sp = add("answer", cmd_human, "record the user's answer to a question", [scoped])
    sp.add_argument("question")
    sp.add_argument("--user-said", required=True, help="the user's own words")
    sp = add("decide", cmd_human, "record a decision the user made", [scoped])
    sp.add_argument("--user-said", required=True)
    sp = add("human", cmd_human, "record a typed human event", [scoped])
    sp.add_argument("--kind", required=True, help="answer, decision, env-hint or correction")
    sp.add_argument("text")
    sp = add("block", cmd_human, "block the run", [scoped])
    sp.add_argument("--kind", required=True, help="question, decision, infra or tooling")
    sp.add_argument("--reason", required=True)
    sp = add("unblock", cmd_human, "resolve a blocker", [scoped])
    sp.add_argument("blocker")
    sp.add_argument("--decision", help="a recorded decision (Q-n or D-n), consumed once")
    sp = add("fetch", cmd_fetch, "acquire a contract through the configured adapter", [scoped])
    sp.add_argument("kind")
    sp.add_argument("id")
    sp.add_argument("--repo")
    sp.add_argument("--refresh", action="store_true", help="a change or pipeline read again after the ship gate, for the feedback phase")
    sp = add("ingest", cmd_ingest, "validate a contract the agent wrote, or --check stale raws", [scoped])
    sp.add_argument("kind", nargs="?")
    sp.add_argument("--raw", metavar="FILE")
    sp.add_argument("--contract", metavar="FILE")
    sp.add_argument("--stdin", action="store_true", help="read the contract data from stdin")
    sp.add_argument("--check", action="store_true", help="list raws that changed since they were acquired")
    sp.add_argument("--refresh", action="store_true", help="a change or pipeline read again after the ship gate, for the feedback phase")
    mp = sub.add_parser("media", help="record ticket media as seen or unseen").add_subparsers(dest="sub", required=True)
    sp = mp.add_parser("seen", parents=[scoped])
    sp.set_defaults(func=cmd_media)
    sp.add_argument("attachment")
    sp.add_argument("--file", required=True, help="file under the run's media folder")
    sp = mp.add_parser("unseen", parents=[scoped])
    sp.set_defaults(func=cmd_media)
    sp.add_argument("attachment")
    sp.add_argument("--question", required=True, help="a question opened with --ref attachment:<id>")
    pp = sub.add_parser("plan", help="print an example plan, or amend the locked plan").add_subparsers(dest="sub", required=True)
    sp = pp.add_parser("example", parents=[common])
    sp.set_defaults(func=cmd_plan)
    sp = pp.add_parser("amend", parents=[scoped])
    sp.set_defaults(func=cmd_plan)
    sp.add_argument("--reason", required=True, help="why the locked plan or config changed")
    sp.add_argument("--decision", help="a recorded user decision (Q-n or D-n); it exempts this amend from the loop budget, once")
    sp.add_argument("--resolves", help="round:id[,round:id] open minor findings of the delivery this checks-only amend closes; it spends no loop")
    for name, func, helptext in (("verify", cmd_verify, "run the checks at HEAD and record evidence"),
                                 ("reproduce", cmd_reproduce, "bug runs: run the reproducing checks on the base")):
        sp = add(name, func, helptext, [scoped])
        sp.add_argument("--check", metavar="ID", help="run only this declared check")
        sp.add_argument("--repo", help="run only the checks of this repo")
        sp.add_argument("--fresh", action="store_true", help="ignore reuse and run everything selected")
        if name == "verify":
            sp.add_argument("--no-retry", action="store_true", help="do not retry an assertion failure once")
            sp.add_argument("--scoped", action="store_true", help="quality checks run their scoped template on the changed files (never satisfies a gate)")
            sp.add_argument("--estimate", action="store_true", help="print reuse or run, with the median duration, per check; runs nothing")
            sp.add_argument("--mirror", action="store_true", help="hotfix: run the mirror: true checks from each mirror worktree")
    sp = add("baseline", cmd_baseline, "record the baseline of the quality checks at the branch point", [scoped])
    sp.add_argument("--check", metavar="ID")
    sp.add_argument("--repo")
    sp.add_argument("--fresh", action="store_true", help="take the baseline again")
    sp = add("feedback", cmd_feedback, "turn unresolved change threads and failed pipeline jobs into findings", [scoped])
    sp.add_argument("--decision", help="a recorded user decision (Q-n or D-n); it exempts this feedback round from the loop budget, once")
    sp.add_argument("--no-fetch", action="store_true", help="read the contracts already ingested; do not call the adapters")
    sp.add_argument("--dismiss", metavar="FINDING", help="a thread finding (F1 or thread:<id>) the user decided needs no change; needs --decision")
    sp = add("metrics", cmd_metrics, "time per phase, loops, blocked hours and gate failures of a run", [scoped])
    sp.add_argument("run_id", nargs="?")
    sp.add_argument("--all", action="store_true", help="aggregate every run of the project")
    sp.add_argument("--since", metavar="DATE", help="with --all: runs started on or after this date (YYYY-MM-DD)")
    sp.add_argument("--tokens", action="store_true", help="record the tokens of --session through the [metrics] tokens adapter")
    sp.add_argument("--session", help="the harness session id given to the tokens adapter")
    rv = sub.add_parser("review", help="record a review, or print an example").add_subparsers(dest="sub", required=True)
    sp = rv.add_parser("example", parents=[common])
    sp.set_defaults(func=cmd_review)
    sp = rv.add_parser("queue", parents=[common], help="changes waiting for the user's review")
    sp.set_defaults(func=cmd_review_run)
    sp.add_argument("--file", metavar="FILE", help="the change_list data as JSON, instead of the adapter")
    sp = rv.add_parser("start", parents=[common], help="start a review run per change (a parent for several)")
    sp.set_defaults(func=cmd_review_run)
    sp.add_argument("changes", nargs="+", metavar="CHANGE")
    sp.add_argument("--repo")
    sp.add_argument("--ticket", help="the linked ticket key (default: review-<change id>)")
    sp = rv.add_parser("report", parents=[scoped], help="record the verdict and the neutral intents of a review run")
    sp.set_defaults(func=cmd_review_run)
    sp.add_argument("--file", required=True, metavar="FILE", help="verdict (ok, not-ok, incomplete), summary, findings, comment_md")
    sp = rv.add_parser("fix", parents=[scoped], help="turn the review run into a ticket run on the change branch")
    sp.set_defaults(func=cmd_review_run)
    sp = rv.add_parser("record", parents=[scoped])
    sp.set_defaults(func=cmd_review)
    sp.add_argument("--kind", required=True, help="code (bound to the plan without checks), qa (bound to the full plan) or uat (the browser exploration of a change with a screen)")
    sp.add_argument("--file", required=True, help="the review as JSON (factory review example)")
    sp.add_argument("--decision", help="a recorded user decision (Q-n or D-n); it exempts this CHANGES round from the loop budget, once")
    sh = sub.add_parser("ship", help="plan the ship intents, or verify the readback").add_subparsers(dest="sub", required=True)
    sp = sh.add_parser("plan", parents=[scoped])
    sp.set_defaults(func=cmd_ship)
    sp.add_argument("--ticket", choices=("none", "comment", "transition", "both"), help="ticket writes to plan (default: [ship] ticket)")
    sp.add_argument("--update", action="store_true", help="re-plan the body and head of changes that already exist")
    sp.add_argument("--allow-behind", action="store_true", help="plan although the target has commits HEAD lacks (needs --decision)")
    sp.add_argument("--decision", help="a recorded user decision (Q-n or D-n) for --allow-behind, consumed once")
    sp.add_argument("--pipeline", action="store_true", help="also plan a pipeline readback (always planned with require_pipeline)")
    sp = sh.add_parser("verify", parents=[scoped])
    sp.set_defaults(func=cmd_ship)
    ep_ = sub.add_parser("epic", help="plan an epic, list its ready children, plan its ship").add_subparsers(dest="sub", required=True)
    for name in ("plan", "status", "ship"):
        sp = ep_.add_parser(name, parents=[scoped])
        sp.set_defaults(func=cmd_epic)
        if name == "ship":
            sp.add_argument("ship", choices=("plan", "verify"))
    sp = add("confirm", cmd_confirm, "record the user's confirmation of a human check or of an agent-written change or pipeline contract", [scoped])
    sp.add_argument("target", help="a human check id (CHK-3) or <kind>:<id>, e.g. change:42")
    sp.add_argument("--user-said", required=True)
    sp.add_argument("--rejected", action="store_true", help="the user rejected the human check: a finding of the delivery, the run goes back to build (one loop)")
    sp = add("waive", cmd_confirm, "record the user's waiver of one pipeline", [scoped])
    sp.add_argument("target", help="pipeline:<id>")
    sp.add_argument("--user-said", required=True)
    ep = sub.add_parser("env", help="start, stop and inspect the env of a repo").add_subparsers(dest="sub", required=True)
    for name, helptext in (("up", "start a repo's env (and what it depends on) from the run worktree"), ("down", "stop the env this run started"),
                           ("health", "probe the health URL"), ("status", "who holds each env lock"), ("logs", "tail the env log"),
                           ("seed", "run the seed command with the run's data prefix"), ("reset", "run the reset command with the run's data prefix")):
        sp = ep.add_parser(name, help=helptext, parents=[scoped])
        sp.set_defaults(func=cmd_env)
        sp.add_argument("repo", nargs="?")
        if name == "up":
            sp.add_argument("--restart", action="store_true", help="stop this run's env of the repo first and start it again")
            sp.add_argument("--wait", type=float, metavar="S", help="queue up to S seconds for another run's env lock")
            sp.add_argument("--user", help="login user slug (state file and <KEY>_<SLUG> secrets)")
            sp.add_argument("--slot", type=int, metavar="N", help="serve on the ports of slot N (local.toml [repo.<name>.slots] port_offset), with its own lock and login state")
        elif name == "logs":
            sp.add_argument("--tail", type=int, default=40)
    dp = sub.add_parser("design", help="design frames: add an approximate image, expect skeleton, review, refresh").add_subparsers(dest="sub", required=True)
    for name, helptext in (("add", "store an approximate design PNG and write a frame skeleton"), ("check", "validate every ingested frame and image"),
                           ("expect", "append a style-map entry from the facts of a frame node"), ("review", "record the user's review of an approx frame"),
                           ("refresh", "re-acquire an exact frame and record whether it moved")):
        sp = dp.add_parser(name, help=helptext, parents=[scoped])
        sp.set_defaults(func=cmd_design)
        if name == "add":
            sp.add_argument("png")
            sp.add_argument("--name", required=True)
            sp.add_argument("--id", help="frame and image id (default: derived from the name)")
        elif name != "check":
            sp.add_argument("frame")
        if name == "expect":
            sp.add_argument("--node", required=True)
            sp.add_argument("--selector", required=True, help="CSS selector of the element that implements the node")
        elif name in ("review", "refresh"):
            sp.add_argument("--user-said", required=name == "review", help="the user's own words" + (" (needed without a design adapter)" if name == "refresh" else ""))
    sp = add("mirror", cmd_mirror, "hotfix: cherry-pick the fix onto a target (or `diff`: compare the mirror with the base fix)", [scoped])
    sp.add_argument("words", nargs="+", metavar="<repo> | diff [<repo>]")
    sp.add_argument("--to", metavar="TARGET", help="the mirror target name")
    sp.add_argument("--ticket", help="the ticket key of this target's change (default: the run ticket)")
    sp.add_argument("--decision", help="diff: a recorded user decision naming every divergent file")
    up = sub.add_parser("uat", help="UAT in the browser: run an exploration script in the served env, logged in").add_subparsers(dest="sub", required=True)
    sp = up.add_parser("run", parents=[scoped])
    sp.set_defaults(func=cmd_uat)
    sp.add_argument("script", help="a spec under <run>/uat/ for the bundled runner (screenshots go to the run's artifacts)")
    sp.add_argument("--repo", help="the repo whose env serves the screen (needed when several have one)")
    sp = add("wait", cmd_wait, "wait for a file, a command or a local URL (600 s cap)")
    sp.add_argument("--file")
    sp.add_argument("--cmd")
    sp.add_argument("--url")
    sp.add_argument("--timeout", type=float, default=60, metavar="S")
    sp = add("hook", cmd_hook, "host hook entry point (installed by init --hooks): reads the tool call on stdin")
    sp.add_argument("event", choices=("pre-tool",))
    sp = add("gate", cmd_gate, "run a gate (reads only; records pass or fail)", [scoped])
    sp.add_argument("name")
    return p
